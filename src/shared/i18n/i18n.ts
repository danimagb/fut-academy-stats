export const I18N: Readonly<Record<Lang, Readonly<Record<MessageKey, string>>>> = { en, pt };

let current: Lang = 'en';

/** The language strings are shown in. */
export function getLang(): Lang {
  return current;
}

/** Changes the language (the caller saves the choice and re-renders). */
export function setLang(value: Lang): void {
  current = value;
}

/** The string for `key` in the current language, with `{name}` placeholders filled from `vars`. */
export function t(key: string, vars: Readonly<Record<string, string | number>> = {}): string {
  const s = I18N[current][key as MessageKey] ?? I18N.en[key as MessageKey] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** `key` for one (with "1" appended, e.g. teamsN1) or `key` for any other `n`, with `{n}` filled. */
export function plural(key: string, n: number): string {
  return t(n === 1 ? `${key}1` : key, { n });
}

/** Locale for dates and numbers in the current language. */
export function locale(): string {
  return current === 'pt' ? 'pt-PT' : 'en-GB';
}
